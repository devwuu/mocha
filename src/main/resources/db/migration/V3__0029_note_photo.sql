-- 노트↔사진 연결 (ref: specs/coffee-note-agent/changes/0029-app-interface/tasks.md TΔ8b, delta.md#D-5,
--                       plan.md#ADR-79 — ADR-32 "사진은 DB에 기록하지 않는다" 폐기)
--
-- 종전에는 아카이브 폴더 경로 규약(photos/<노트폴더>/<date>/)이 노트·날짜와의 **유일한** 연결이었다.
-- 갤러리(D-5)가 원두 봉투 사진을 노트 카드로 보여주려면 "어떤 노트에 어떤 사진이 있는가"를 질의할 수
-- 있어야 하고, 폴더 스캔은 DB와 파일시스템이 따로 노는 답이라(0028 Q-13 ㉠) 행으로 들인다.
--
-- POLICY: 사진 바이트의 정본은 여전히 **파일**이고 이 테이블은 그 파일을 노트에 잇는 **색인**이다
--         (ref: plan.md#ADR-79). 그래서 색인 삽입 실패가 노트 커밋을 되돌리지 않고(사진은 폴더에
--         남는다), 노트 삭제에서도 행 삭제가 파일 삭제보다 **앞선다** — 어느 실패 조합에서도 사진
--         바이트가 조용히 사라지지 않는 쪽으로 순서를 고정한 것이다(백엔드 CLAUDE.md §3
--         "DB 쓰기와 파일 쓰기는 같은 원자 단위가 아니다").
--
-- POLICY: 참조 축은 (note_id, tasted_on)이고 **entry.id가 아니다** (사용자 확정 2026-08-01).
--         엔트리는 저장 때마다 통째로 교체되므로(ADR-4·59 — 삭제 후 재삽입) entry.id가 재발급된다.
--         사진 행이 그것을 가리키면 재저장 한 번에 전부 고아가 되는데, FK가 없어(ADR-75) DB는 아무
--         말도 하지 않는다. 날짜는 노트 안에서 유일 키라(V-10) 그 사정이 없다.
--
-- 테이블명 단수·FK 미사용·자식 인덱스는 UNIQUE가 겸한다 — V1의 POLICY 3종을 그대로 따른다.
CREATE TABLE note_photo (
    id        BIGSERIAL PRIMARY KEY,
    note_id   BIGINT  NOT NULL,
    -- 어느 날 시음의 사진인가 — 아카이브 폴더의 <date> 세그먼트와 같은 값이다.
    tasted_on DATE    NOT NULL,
    -- 같은 (노트, 날짜) 안의 순서. 파일명 오름차순(= PhotoStore 커밋 순서)을 보존한다.
    seq       INTEGER NOT NULL,
    -- V-4 어휘 승계: photos/ 로 시작하는 **상대 경로**만 넣는다. 절대 경로·URL은 만들지 않는다.
    -- 폴더 접미는 생성 시점 스냅샷이라(ADR-75) 지금 이름으로 재계산할 수 없다 — 그래서 계산 결과가
    -- 아니라 실제로 쓴 경로를 통째로 남긴다(0028 파생 결정 2가 남긴 한계가 닫히는 지점).
    path      TEXT    NOT NULL,
    UNIQUE (note_id, tasted_on, seq)
);
